"""Generates both sides of the wire protocol from wire/schema.json.

    xrc codegen            # writes xrcollect/protocol_gen.py and web/src/protocol.gen.ts
    xrc codegen --check    # exit 1 if the files on disk differ (tests/test_protocol.py does the same)

The generated files hold every constant, size and field offset. The hand-written parts (protocol.py dataclasses,
web/src/protocol.ts packer) only use those names, so a layout change is one edit in schema.json.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SCHEMA = HERE / "schema.json"
PY_OUT = HERE.parent / "protocol_gen.py"
TS_OUT = ROOT / "web" / "src" / "protocol.gen.ts"

STRUCT = {"u8": ("B", 1), "u16": ("H", 2), "u32": ("I", 4), "f64": ("d", 8)}
TS_GET = {"u8": "Uint8", "u16": "Uint16", "u32": "Uint32", "f64": "Float64"}


def _load() -> dict:
    return json.loads(SCHEMA.read_text())


def _count(expr, consts: dict) -> int:
    return int(expr) if isinstance(expr, int) else int(eval(expr, {"__builtins__": {}}, dict(consts)))  # noqa: S307


def layout(schema: dict | None = None) -> dict:
    """Everything derived from the schema: constants, header formats and offsets, float offsets."""
    s = schema or _load()
    c = dict(s["constants"])
    out = {"VERSION": s["version"], **c}
    for i, b in enumerate(s["buttons"]):
        out[f"B_{b}"] = i
    for alias, joint in s["joint_aliases"].items():
        out[alias] = s["hand_joints"].index(joint)
    for which in ("input_header", "pose_header"):
        fmt, off, offsets = "<", 0, {}
        for f in s[which]:
            ch, size = STRUCT[f["fmt"]]
            fmt += ch
            offsets[f["name"]] = (off, f["fmt"])
            off += size
        out[f"{which.upper()}_FMT"] = fmt
        out[f"{which.upper()}_BYTES"] = off
        out[f"_{which}_offsets"] = offsets
    hand, off = {}, 0
    for f in s["hand"]:
        n = _count(f["floats"], c)
        hand[f["name"]] = (off, n)
        off += n
    out["HAND_FLOATS"] = off
    out["_hand"] = hand
    body, off = {}, 0
    for f in s["input_body"]:
        n = _count(f["floats"], c)
        body[f["name"]] = (off, n)
        off += n
    out["_body"] = body
    out["HANDS_OFFSET"] = off
    out["INPUT_FLOATS"] = off + 2 * out["HAND_FLOATS"]
    out["INPUT_BYTES"] = out["INPUT_HEADER_BYTES"] + 4 * out["INPUT_FLOATS"]
    out["_hand_joints"] = s["hand_joints"]
    return out


def render_python(L: dict) -> str:
    lines = ['"""GENERATED by xrcollect/wire/codegen.py from wire/schema.json. Do not edit."""', "",
             "import struct", ""]
    for k, v in L.items():
        if k.startswith("_"):
            continue
        lines.append(f"{k} = {v!r}")
    lines += ["", "INPUT_HEADER = struct.Struct(INPUT_HEADER_FMT)", "POSE_HEADER = struct.Struct(POSE_HEADER_FMT)", ""]
    lines.append("# float offsets inside one hand block: name -> (offset, count)")
    lines.append(f"HAND_FIELDS = {L['_hand']!r}")
    lines.append("# float offsets of the fields before the two hand blocks")
    lines.append(f"BODY_FIELDS = {L['_body']!r}")
    lines.append(f"HAND_JOINTS = {L['_hand_joints']!r}")
    return "\n".join(lines) + "\n"


def render_ts(L: dict) -> str:
    lines = ["// GENERATED by xrcollect/wire/codegen.py from wire/schema.json. Do not edit.", ""]
    for k, v in L.items():
        if k.startswith("_") or isinstance(v, str):
            continue
        lines.append(f"export const {k} = {v};")
    lines.append("")
    for which in ("input_header", "pose_header"):
        entries = ", ".join(f"{name}: {off}" for name, (off, _) in L[f"_{which}_offsets"].items())
        lines.append(f"export const {which.upper()}_OFFSETS = {{ {entries} }} as const;")
    for name, table in (("HAND_FIELDS", L["_hand"]), ("BODY_FIELDS", L["_body"])):
        entries = ", ".join(f"{k}: {{ offset: {o}, count: {n} }}" for k, (o, n) in table.items())
        lines.append(f"export const {name} = {{ {entries} }} as const;")
    joints = ", ".join(json.dumps(j) for j in L["_hand_joints"])
    lines.append(f"export const HAND_JOINTS: XRHandJoint[] = [{joints}];")
    return "\n".join(lines) + "\n"


def generate(check: bool = False) -> bool:
    """Write the generated files (or, with check, only compare). Returns True if they are up to date."""
    L = layout()
    ok = True
    for path, text in ((PY_OUT, render_python(L)), (TS_OUT, render_ts(L))):
        current = path.read_text() if path.exists() else None
        if current != text:
            ok = False
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    return ok


if __name__ == "__main__":
    import sys

    up_to_date = generate(check="--check" in sys.argv)
    print("up to date" if up_to_date else ("OUT OF DATE" if "--check" in sys.argv else "written"))
    sys.exit(0 if up_to_date or "--check" not in sys.argv else 1)
